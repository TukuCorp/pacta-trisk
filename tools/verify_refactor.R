#' Is a gated HTML file's working-tree content equal to its committed content
#' once generated timestamps, dates and git SHAs are normalized away?
#'
#' Compares against the HEAD blob rather than a stored digest, so the check has
#' no state to keep in sync. A path that does not exist at HEAD is a brand-new
#' report, which is an addition rather than drift.
#'
#' @param path character(1) — repo-relative path.
#' @param root character(1) — repo root.
#' @return logical(1) — TRUE when the only differences are timestamp-class.
.html_is_timestamp_only <- function(path, root = ".") {
  disk_path <- file.path(root, path)
  if (!file.exists(disk_path)) return(FALSE)

  # Capture `git show` into a file rather than via stdout = TRUE. These reports
  # embed base64 PNG payloads as single very long lines, and reading them
  # through an R pipe splits those lines at a buffer boundary -- which would
  # reinsert newlines mid-payload and make an untouched report read as drift.
  tmp <- tempfile("head_blob_")
  on.exit(unlink(tmp), add = TRUE)
  status <- tryCatch(
    suppressWarnings(system2(
      "git", args = c("-C", root, "show", paste0("HEAD:", path)),
      stdout = tmp, stderr = FALSE
    )),
    error = function(e) 1L
  )
  # Not in HEAD (new file), or git could not resolve the blob: an addition, not
  # drift.
  if (!identical(as.integer(status), 0L) || !file.exists(tmp)) return(TRUE)
  if (isTRUE(file.info(tmp)$size == 0)) return(TRUE)

  # Trailing-whitespace-trimmed so a missing/extra final newline -- an artifact
  # of how each side is written, not a real difference -- never reads as drift.
  disk_norm <- .trim_trailing(normalize_report_html(.read_utf8(disk_path)))
  head_norm <- .trim_trailing(normalize_report_html(.read_utf8(tmp)))
  identical(disk_norm, head_norm)
}

#' Drop trailing whitespace at the very end of a string.
#' @param x character(1).
#' @return character(1).
.trim_trailing <- function(x) sub("[ \t\r\n]+$", "", paste(x, collapse = "\n"))

#' Classify a single changed path into a drift bucket.
#' @param path character, a repo-relative path as reported by `git diff --name-only`.
#' @param volatile_basenames character vector of basenames known to carry only
#'   a regenerated run-id/run-path value between unmodified runs.
#' @param gated_html_paths character vector of repo-relative HTML deliverables
#'   compared by normalized content instead of being ignored.
#' @param root character, repo root used to resolve `path` and to run git.
#' @return character, one of "png-noise", "timestamp-class", "volatile", "drift".
classify_path <- function(path, volatile_basenames = VOLATILE_BASENAMES,
                          gated_html_paths = GATED_HTML_PATHS, root = ".") {
  ext <- tolower(tools::file_ext(path))
  base <- basename(path)
  if (identical(ext, "png")) {
    return("png-noise")
  }
  if (identical(ext, "html")) {
    # Wave 4 PHASE-01: a gated deliverable is compared, not assumed.
    if (gsub("\\\\", "/", path) %in% gated_html_paths) {
      return(if (.html_is_timestamp_only(path, root)) "timestamp-class" else "drift")
    }
    return("timestamp-class")
  }
  if (base %in% TIMESTAMP_BASENAMES) {
    return("timestamp-class")
  }
  if (base %in% volatile_basenames) {
    return("volatile")
  }
  # Wave 3 PHASE-04: history/ is append-only by construction
  # (R/run_history.R::record_run_history() refuses to overwrite an existing
  # run directory) -- every diff under it is a brand-new run being added,
  # never a modification of a prior one, so it is expected churn rather
  # than genuine drift.
  normalized <- gsub("\\\\", "/", path)
  if (identical(normalized, "history") || startsWith(normalized, "history/")) {
    return("timestamp-class")
  }
  "drift"
}

